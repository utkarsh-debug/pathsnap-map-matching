"""Builds docs/evidence_section4_logreg_knn.md from the result files (no number is typed by hand).
Run: python -m docs.make_evidence_section4_logreg_knn

This is an EVIDENCE PACK, not report text: facts and numbers the report must be written from. The explanations
(why an algorithm suits the problem, strengths/limitations, interpretation) have to be written by the team in its own words.
"""
import json

import pandas as pd

from src.config import RESULTS_DIR, ROOT

c = pd.read_csv(RESULTS_DIR / "model_comparison.csv").set_index("model")
f = pd.read_csv(RESULTS_DIR / "cv_folds.csv")
tu = pd.read_csv(RESULTS_DIR / "tuned_vs_untuned.csv").set_index("model")
bo = json.loads((RESULTS_DIR / "bo_best_params.json").read_text())
sp = json.loads((RESULTS_DIR / "bo_search_space.json").read_text())
tr = pd.read_csv(RESULTS_DIR / "bo_trials.csv")
tr = tr[tr.state == "COMPLETE"].sort_values("number")
sens = pd.read_csv(RESULTS_DIR / "sensitivity_exclusion.csv")
cfg = json.loads((RESULTS_DIR / "logs" / "train_models_config.json").read_text())

L = []
w = L.append
w("# Evidence pack: report section 4 (Bayesian optimisation) and models LogisticRegression, KNN")
w("")
w("Generated by `docs/make_evidence_section4_logreg_knn.py` from `results/*.csv|json`. Facts and numbers only: the explanations, "
  "reasoning and conclusions in the report must be written by the team. Partitions: *CV* = 5-fold GroupKFold by trip over the 80 "
  "training trips; *student-test* = the 10 student-test trips. No evaluator data is used anywhere.")
w("")
w("## Section 4: Bayesian hyperparameter optimisation (chosen model: %s)" % bo["model"])
w("")
w("1. **Hyperparameters in the search:** " + ", ".join(sp["space"]) + ".")
w("2. **Ranges / distributions and why:**")
w("")
w("| hyperparameter | range | justification recorded in `bo_search_space.json` |")
w("|---|---|---|")
for k, v in sp["space"].items():
    w(f"| {k} | {v} | {sp['justification'].get(k, '')} |")
w("")
w(f"3. **Objective:** {sp['objective']}.")
w(f"4. **Trials:** {bo['n_trials']} ({bo['sampler']}). Search cost {bo['search_seconds']:.0f} s ({bo['search_seconds']/60:.1f} min); "
  f"{len(tr)} trials completed.")
w("5. **Best hyperparameters (trial %d):**" % int(tr.loc[tr.value.idxmax(), "number"]))
w("")
for k, v in bo["best_params"].items():
    w(f"   - {k} = {v:.6g}")
w("")
w("6. **Tuned vs untuned** (same folds, same metrics, same partitions; `results/tuned_vs_untuned.csv`):")
w("")
u, t = tu.loc[f"{bo['model']}_untuned"], tu.loc[f"{bo['model']}_tuned"]
rows = [("CV Top-1 (objective)", "cv_top1"), ("CV observation macro F1", "cv_obs_macro_f1"), ("CV candidate macro F1", "cv_cand_macro_f1"),
        ("CV observation log loss", "cv_obs_log_loss"), ("Student Top-1", "student_top1"),
        ("Student observation macro F1", "student_obs_macro_f1"), ("Student candidate macro F1", "student_cand_macro_f1"),
        ("Student observation log loss", "student_obs_log_loss"), ("Student candidate log loss", "student_cand_log_loss"),
        ("Student route continuity", "student_route_continuity"), ("Training time (s)", "train_time_s"),
        ("Inference per GPS point (ms)", "infer_ms_per_obs")]
w("| metric | untuned | tuned | difference |")
w("|---|---|---|---|")
for name, col in rows:
    w(f"| {name} | {u[col]:.4f} | {t[col]:.4f} | {t[col]-u[col]:+.4f} |")
w("")
w("Facts about the search itself:")
w(f"- Trial CV Top-1 ranges {tr.value.min():.4f} to {tr.value.max():.4f} (median {tr.value.median():.4f}); the 10 random start-up trials "
  f"average {tr[tr.number < 10].value.mean():.4f}, the 30 guided trials {tr[tr.number >= 10].value.mean():.4f}.")
w(f"- Standard deviation of CV Top-1 across the 5 folds (tuned): {t['cv_top1_std']:.4f}; fold 4 contains the two trips whose reference "
  "route does not match the GPS track (see `results/decisions.md`).")
w("- The tuned CV figure is the best of the %d trials chosen on those same folds (selection bias)." % len(tr))
w("- Sensitivity of the tuned model to the 2 unreliable training trips (`results/sensitivity_exclusion.csv`):")
for _, r in sens.iterrows():
    w(f"  - {r.training_set}: student Top-1 {r.student_top1:.4f}, observation macro F1 {r.student_obs_macro_f1:.4f}, observation log loss {r.student_obs_log_loss:.4f}")
w("")
w("Figures: `results/figures/bo_history_importance.png`, `results/figures/bo_tuned_vs_untuned.png`. Raw trials: `results/bo_trials.csv`.")
w("")

for m, loss in (("LogisticRegression", "binary cross-entropy (log loss) plus an L2 penalty on the weights, minimised by the lbfgs solver "
                 "(no class weighting)"),
                ("KNN", "none: KNN is non-parametric and is not trained by minimising a loss; there is nothing to fit, "
                 "the training rows are stored and each prediction is a distance-weighted vote of the 25 nearest rows")):
    r = c.loc[m]
    fm = f[f.model == m].sort_values("fold")
    w(f"## Model: {m} ({r.family})")
    w("")
    w("### A. Model understanding: facts from our experiments to build your answer on")
    w(f"- Inference cost: {r.infer_ms_per_obs:.4f} ms per GPS point; training time {r.train_time_s:.1f} s on {int(fm.train_rows.iloc[0]):,} rows per fold.")
    w(f"- Student-test observation log loss {r.student_obs_log_loss:.4f} (best model in the comparison: {c.student_obs_log_loss.min():.4f} for "
      f"{c.student_obs_log_loss.idxmin()}); student-test Top-1 {r.student_top1:.4f} (best {c.student_top1.max():.4f}, {c.student_top1.idxmax()}).")
    w(f"- Rank among the 6 models: CV Top-1 {int(c.cv_top1_mean.rank(ascending=False)[m])}, student Top-1 {int(c.student_top1.rank(ascending=False)[m])}, "
      f"student observation log loss {int(c.student_obs_log_loss.rank(ascending=True)[m])} (1 = best).")
    w("- Think about: what decision boundary this model can represent on the 19 features; how it deals with the strongly non-linear "
      "distance/heading interaction; how well its probabilities suit the HMM emission scores; its cost inside the API.")
    w("")
    w("### B. Training and configuration")
    w(f"- Initial hyperparameters (config): {cfg[m]['config']}; random seed 42; trained on {cfg[m]['train_frac']*100:.0f}% of the training rows.")
    w(f"- Loss / optimisation objective: {loss}.")
    w("")
    w("### C. Experimental results")
    w("**Student-test (10 trips; `results/model_comparison.csv`)**")
    w("")
    w("| metric | value |")
    w("|---|---|")
    for name, col in (("observation-level Top-1 accuracy", "student_top1"), ("observation-level macro F1", "student_obs_macro_f1"),
                      ("observation-level macro precision", "student_obs_macro_precision"), ("observation-level macro recall", "student_obs_macro_recall"),
                      ("observation-level log loss", "student_obs_log_loss"), ("candidate-level macro F1", "student_cand_macro_f1"),
                      ("candidate-level accuracy", "student_cand_accuracy"), ("candidate-level log loss", "student_cand_log_loss"),
                      ("route continuity", "student_route_continuity")):
        w(f"| {name} | {r[col]:.4f} |")
    w("")
    w("**Cross-validation (80 training trips, 5 folds)**")
    w("")
    w("| fold | Top-1 (all trips) | Top-1 (reliable trips) | obs. macro F1 | obs. log loss | train-sample Top-1 | train cand. log loss | val cand. log loss |")
    w("|---|---|---|---|---|---|---|---|")
    for _, x in fm.iterrows():
        w(f"| {int(x.fold)} | {x.top1:.4f} | {x.rel_top1:.4f} | {x.obs_macro_f1:.4f} | {x.obs_log_loss:.4f} | {x.train_top1:.4f} | {x.train_cand_log_loss:.4f} | {x.cand_log_loss:.4f} |")
    w(f"| mean | {r.cv_top1_mean:.4f} | {r.cv_rel_top1_mean:.4f} | {r.cv_obs_macro_f1_mean:.4f} | {r.cv_obs_log_loss_mean:.4f} | {r.cv_train_top1_mean:.4f} | {r.cv_train_cand_log_loss_mean:.4f} | {r.cv_cand_log_loss_mean:.4f} |")
    w("")
    w("Evidence for the overfitting / underfitting question (C9):")
    w(f"- Candidate log loss, train (in-fold sample) vs validation (held-out trips): {r.cv_train_cand_log_loss_mean:.4f} vs {r.cv_cand_log_loss_mean:.4f}.")
    w(f"- Top-1 on the train sample vs held-out reliable trips: {r.cv_train_top1_mean:.4f} vs {r.cv_rel_top1_mean:.4f}. Caution: the train sample still contains the 2 "
      "noisy-label trips, which lowers train Top-1 for the non-memorising models, so use the log-loss comparison as the cleaner signal.")
    w("- Fold 4 holds trips 33 and 54 (unreliable reference route): its Top-1 is ~0.42 for every model and ~0.82 with those trips removed from the evaluation.")
    w(f"- Supporting fact: in fold 4 the training part contains neither unreliable trip, and the train-sample Top-1 there is {fm[fm.fold == 4].train_top1.iloc[0]:.4f}, "
      f"against a mean of {fm[fm.fold < 4].train_top1.mean():.4f} in folds 0-3 where those trips are in the training part.")
    w("- Epoch-wise training/validation curves exist only for LightGBM, XGBoost and the MLP, so none are shown for this model.")
    w("- Figures: `results/figures/cmp_overfitting.png`, `cmp_confusion_matrices.png`, `cmp_stability_continuity_time.png`.")
    w("")

out = ROOT / "docs" / "evidence_section4_logreg_knn.md"
out.write_text("\n".join(L), encoding="utf-8")
print("wrote", out, len(L), "lines")
